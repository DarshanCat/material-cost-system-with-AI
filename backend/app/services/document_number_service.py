class SequenceExhaustedError(HTTPException):
    """Raised when sequence allocation exceeds the configured padding width."""

    def __init__(self, doc_type: Union[DocumentType, str], date_str: str, max_allowed: int):
        type_str = doc_type.value if isinstance(doc_type, DocumentType) else str(doc_type)
        super().__init__(
            status_code=status.HTTP_409_CONFLICT,
            detail=(
                f"Sequence capacity exhausted for {type_str} on {date_str}. "
                f"Maximum supported sequence number is {max_allowed}."
            ),
        )


