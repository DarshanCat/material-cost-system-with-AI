def _extract_sequence_number(val: str, prefix: str) -> int:
    """Extracts integer sequence suffix from a document number string."""
    if not val or not val.startswith(prefix):
        return 0
    suffix = val[len(prefix):]
    match = re.match(r"^(\d+)", suffix)
    if match:
        try:
            return int(match.group(1))
        except ValueError:
            return 0
    return 0


def generate_document_number(
    db: Session,
    doc_type: DocumentType,
    target_date: Optional[Union[date, datetime]] = None,
    padding: Optional[int] = None,
) -> str:
    """
    Generates a deterministic sequential document number: {PREFIX}{YYYYMMDD}-{XXXX}.

    Architectural guarantees:
    1. Uses a database-side aggregate (MAX) via index scan rather than loading all rows into Python.
    2. Scans pending uncommitted objects in the current session (db.new) to guarantee distinct
       monotonic increments during multi-line operations prior to flush.
    3. Strictly enforces configured sequence width boundaries (e.g. 4-digit limit 9999, 6-digit limit 999999),
       raising SequenceExhaustedError instead of silently formatting malformed widths.
    4. Note: While MAX() + 1 determines the next optimistic sequential value, database-level unique
       constraints combined with savepoint retry (execute_with_document_number_retry) provide the
       authoritative safeguard against race conditions.
    """
    config = DOCUMENT_CONFIGS[doc_type]
    pad = padding if padding is not None else config.padding

    if target_date is None:
        target_date = datetime.now(timezone.utc).date()
    elif isinstance(target_date, datetime):
        target_date = target_date.date()

    date_str = target_date.strftime("%Y%m%d")
    full_prefix = f"{config.prefix}{date_str}-"

    # 1. Database-side aggregate: query MAX() for this specific date prefix.
    # Because document numbers use fixed zero-padding, lexicographical MAX corresponds to numerical MAX.
    persisted_max = db.scalar(
        select(func.max(config.column_attr)).where(config.column_attr.like(f"{full_prefix}%"))
    )

    max_seq = 0
    if persisted_max:
        max_seq = _extract_sequence_number(persisted_max, full_prefix)

    # 2. Check pending uncommitted objects in current session (db.new)
    col_name = config.column_name
    for obj in db.new:
        if isinstance(obj, config.model_class):
            val = getattr(obj, col_name, None)
            if val and isinstance(val, str) and val.startswith(full_prefix):
                seq = _extract_sequence_number(val, full_prefix)
                if seq > max_seq:
                    max_seq = seq

    next_seq = max_seq + 1

    # 3. Explicit sequence width boundary check
    max_allowed = (10 ** pad) - 1
    if next_seq > max_allowed:
        raise SequenceExhaustedError(
            doc_type=doc_type,
            date_str=date_str,
            max_allowed=max_allowed,
        )

    return f"{full_prefix}{next_seq:0{pad}d}"


def is_document_number_collision(
    exc: IntegrityError,
    column_name: str,
    table_name: Optional[str] = None,
) -> bool:
    """
    Determines whether an IntegrityError represents a unique constraint violation
    specifically on the document-number column of the specified table.

    Rejects:
    - Foreign key violations (SQLSTATE 23503)
    - Check constraint violations (SQLSTATE 23514)
    - NOT NULL violations (SQLSTATE 23502)
    - Double-posting composite unique constraint (e.g. uq_source_doc_line_posting)
    - Unique violations on any other table or column
    """
    if not isinstance(exc, IntegrityError):
        return False

    col_lower = column_name.lower()
    table_lower = table_name.lower() if table_name else ""
    expected_constraints: Set[str] = {
        f"{table_lower}_{col_lower}_key",
        f"uq_{table_lower}_{col_lower}",
        f"{col_lower}_key",
    }

    # 1. Structured PostgreSQL Driver Diagnostics (psycopg 3 / psycopg 2)
    orig = getattr(exc, "orig", None)
    if orig is not None:
        sqlstate = getattr(orig, "sqlstate", None) or getattr(orig, "pgcode", None)
        if sqlstate is not None:
            # PostgreSQL error code 23505 is UNIQUE_VIOLATION
            if str(sqlstate) != "23505":
                return False

            diag = getattr(orig, "diag", None)
            if diag is not None:
                # Check exact constraint name
                c_name = getattr(diag, "constraint_name", None)
                if c_name:
                    c_name_lower = c_name.lower()
                    if c_name_lower in expected_constraints:
                        return True
                    # A specific constraint was violated, but not our document-number column
                    return False

                # Check column name in diagnostics if available
                diag_col = getattr(diag, "column_name", None)
                if diag_col:
                    return diag_col.lower() == col_lower

                # Check message detail (e.g., "Key (grn_number)=(...) already exists.")
                detail = getattr(diag, "message_detail", None)
                if detail:
                    detail_lower = detail.lower()
                    if f"key ({col_lower})=" in detail_lower or f"({col_lower})=" in detail_lower:
                        return True
                    return False

    # 2. Textual Fallback Matching (SQLite, mocked exceptions, and driver error strings)
    err_str = str(exc).lower()

    # Reject non-uniqueness errors
    if "foreign key" in err_str or "check constraint" in err_str or "not null" in err_str:
        return False

    # Check for SQLite: "UNIQUE constraint failed: table.column"
    match = re.search(r"unique constraint failed:\s*([a-zA-Z0-9_., ]+)", err_str)
    if match:
        failed_fields = [f.strip() for f in match.group(1).split(",")]
        for field in failed_fields:
            if field == f"{table_lower}.{col_lower}" or field == col_lower:
                return True
        return False

    # Check for PostgreSQL textual representations
    if "duplicate key value violates unique constraint" in err_str or "unique_violation" in err_str:
        for cname in expected_constraints:
            if cname.lower() in err_str:
                return True
        if f"key ({col_lower})=" in err_str or f"key ({col_lower}) already exists" in err_str:
            return True
        return False

    # Fallback exact column match in unique error text
    if "unique" in err_str and (f"{table_lower}.{col_lower}" in err_str or f"({col_lower})" in err_str):
        return True

    return False


def execute_with_document_number_retry(
    db: Session,
    doc_type: DocumentType,
    create_fn: Callable[[str], T],
    target_date: Optional[Union[date, datetime]] = None,
    max_retries: int = 5,
) -> T:
    """
    Executes document creation with bounded collision retries.
    Uses SQLAlchemy savepoints (begin_nested) to cleanly isolate failed flush attempts.

    Transactional safety:
    1. Each attempt opens an isolated savepoint (sp = db.begin_nested()).
    2. Successful attempts commit the savepoint (sp.commit()).
    3. Collision failures roll back only the savepoint (sp.rollback()), preserving the outer
       caller transaction and allowing fresh document number generation on the next attempt.
    4. Any non-collision IntegrityError or any other exception (e.g. ValueError, HTTPException)
       immediately rolls back the savepoint (sp.rollback()) and re-raises, leaving the outer
       transaction clean and preventing session corruption or partial dirty records.
    5. If all retries are exhausted by collisions, raises HTTP 409 Conflict.
    """
    config = DOCUMENT_CONFIGS[doc_type]

    for attempt in range(max_retries):
        sp = None
        try:
            sp = db.begin_nested()
            doc_number = generate_document_number(db, doc_type, target_date)
            result = create_fn(doc_number)
            db.flush()
            sp.commit()
            return result
        except IntegrityError as exc:
            if sp is not None:
                sp.rollback()
            # If sp is None, begin_nested() failed during pre-savepoint autoflush on caller's
            # pre-existing session objects. This is an outer-transaction failure, not a collision
            # for this document, and must never be retried.
            if sp is None or not is_document_number_collision(exc, config.column_name, config.table_name):
                # Unrelated integrity error (FK, Check, other unique, or pre-savepoint autoflush) -> do not retry!
                raise
            if attempt == max_retries - 1:
                raise HTTPException(
                    status_code=status.HTTP_409_CONFLICT,
                    detail=(
                        f"Concurrent creation conflict for {config.display_name} "
                        f"after {max_retries} attempts. Please refresh and retry."
                    ),
                ) from exc
        except Exception:
            if sp is not None:
                sp.rollback()
            raise

    # Fallback in case max_retries <= 0
    raise HTTPException(
        status_code=status.HTTP_409_CONFLICT,
        detail=f"Unable to allocate unique document number for {config.display_name}.",
    )


def generate_posting_group_id(source_prefix: str, identifier: Union[int, str, None] = None) -> str:
    """
    Generates a collision-resistant posting group ID strictly within VARCHAR(50).
    Format: POST-{PREFIX}-{ID}-{TIMESTAMP_SECS}-{HEX8}

    Guarantees:
    - Overall length <= 50 characters.
    - Uniqueness suffix (-{TIMESTAMP_SECS}-{HEX8}) is NEVER truncated, even for arbitrarily long source IDs.
    - Long source IDs or prefixes are deterministically truncated from the identifier part to preserve
      the uniqueness suffix and ensure uniqueness properties remain intact.
    """
    ts = datetime.now(timezone.utc).strftime("%Y%m%d%H%M%S")  # 14 chars
    rand_hex = uuid.uuid4().hex[:8]  # 8 chars (4.29 billion combinations per second)
    suffix = f"-{ts}-{rand_hex}"  # 24 chars (1 + 14 + 1 + 8)

    prefix_tag = "POST-"  # 5 chars
    max_prefix_content_len = 50 - len(prefix_tag) - len(suffix)  # 50 - 5 - 24 = 21 chars

    if identifier is not None:
        clean_prefix = str(source_prefix).strip()
        clean_id = str(identifier).strip()
        raw_content = f"{clean_prefix}-{clean_id}"
        if len(raw_content) > max_prefix_content_len:
            avail_for_id = max_prefix_content_len - len(clean_prefix) - 1
            if avail_for_id > 0:
                content = f"{clean_prefix}-{clean_id[:avail_for_id]}"
            else:
                content = raw_content[:max_prefix_content_len]
        else:
            content = raw_content
    else:
        clean_prefix = str(source_prefix).strip()
        content = clean_prefix[:max_prefix_content_len]

    result = f"{prefix_tag}{content}{suffix}"
    assert len(result) <= 50, f"posting_group_id length exceeded 50: {len(result)}"
    return result


def generate_reversal_posting_group_id(original_entry_number: str) -> str:
    """
    Generates a collision-resistant reversal posting group ID strictly within VARCHAR(50).
    Format: REV-{ORIGINAL_ENTRY}-{TIMESTAMP_SECS}-{HEX8}

    Guarantees:
    - Overall length <= 50 characters.
    - Uniqueness suffix (-{TIMESTAMP_SECS}-{HEX8}) is NEVER truncated, even for arbitrarily long entry numbers.
    """
    ts = datetime.now(timezone.utc).strftime("%Y%m%d%H%M%S")  # 14 chars
    rand_hex = uuid.uuid4().hex[:8]  # 8 chars
    suffix = f"-{ts}-{rand_hex}"  # 24 chars

    prefix_tag = "REV-"  # 4 chars
    max_entry_len = 50 - len(prefix_tag) - len(suffix)  # 50 - 4 - 24 = 22 chars

    clean_entry = str(original_entry_number).strip()
    entry_part = clean_entry[:max_entry_len]

    result = f"{prefix_tag}{entry_part}{suffix}"
    assert len(result) <= 50, f"reversal posting_group_id length exceeded 50: {len(result)}"
    return result
