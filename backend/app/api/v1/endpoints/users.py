"""
User administration (Admin only, permission user:manage): create users with a temporary password, approve people
who signed in for the first time, assign or change roles, disable/enable, reset passwords, and read the audit trail.

Only available with AUTH_PROVIDER=identity (the provider that has users and passwords). Temporary passwords are
generated by the server, returned once in the response, and never stored or logged.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Query, status
from pydantic import BaseModel, Field
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.core.auth import get_auth_provider
from app.core.identity_auth import IdentityAdmin, IdentityAdminError, get_identity_admin
from app.core.security import AuthenticatedUser, Permission, require_permission
from app.db.session import get_db
from app.models.app_user import AppUser, AppUserAuditLog, UserStatus
from app.services import user_service as svc

router = APIRouter()


def _require_identity_mode() -> None:
    if get_auth_provider().name != "identity":
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="User administration is not available with this sign-in mode.")


class UserOut(BaseModel):
    id: int
    email: str
    display_name: str
    role: Optional[str]
    department: str
    status: str
    auth_source: str
    must_change_password: bool
    last_login_at: Optional[datetime]
    created_at: datetime
    decided_by: Optional[str]
    decided_at: Optional[datetime]

    model_config = {"from_attributes": True}


class UserList(BaseModel):
    items: list[UserOut]
    total: int


class CreateUserRequest(BaseModel):
    email: str = Field(min_length=3, max_length=254)
    display_name: str = Field(default="", max_length=120)
    role: str
    department: Optional[str] = Field(default=None, max_length=100)


class CreateUserResponse(BaseModel):
    user: UserOut
    temporary_password: str


class ApproveRequest(BaseModel):
    role: str
    department: Optional[str] = Field(default=None, max_length=100)


class RejectRequest(BaseModel):
    reason: str = Field(default="", max_length=500)


class UpdateUserRequest(BaseModel):
    role: Optional[str] = None
    department: Optional[str] = Field(default=None, max_length=100)
    display_name: Optional[str] = Field(default=None, max_length=120)


class AuditOut(BaseModel):
    id: int
    user_email: str
    action: str
    actor: str
    detail: str
    created_at: datetime

    model_config = {"from_attributes": True}


class AuditList(BaseModel):
    items: list[AuditOut]


def _get_user(db: Session, user_id: int) -> AppUser:
    user = db.get(AppUser, user_id)
    if user is None:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="User not found.")
    return user


def _valid_role(value: str):
    try:
        return svc.parse_role(value)
    except ValueError as exc:
        raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY, detail=str(exc))


def _identity_call(fn, *args):
    try:
        return fn(*args)
    except IdentityAdminError as exc:
        raise HTTPException(status_code=status.HTTP_502_BAD_GATEWAY, detail=str(exc))


def _forbid_self(user: AppUser, actor: AuthenticatedUser, what: str) -> None:
    if user.email == actor.user_id:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail=f"You cannot {what} your own account.")


def _keep_one_admin(db: Session, user: AppUser, what: str) -> None:
    if user.status == UserStatus.ACTIVE.value and user.role == "Admin" and svc.count_active_admins(db) <= 1:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail=f"Cannot {what} the last active Administrator.")


@router.get("", response_model=UserList, summary="List users")
def list_users(
    status_filter: Optional[str] = Query(default=None, alias="status"),
    db: Session = Depends(get_db),
    _actor: AuthenticatedUser = Depends(require_permission(Permission.USER_MANAGE)),
) -> UserList:
    _require_identity_mode()
    query = select(AppUser).order_by(AppUser.created_at.desc())
    if status_filter:
        if status_filter not in {s.value for s in UserStatus}:
            raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY, detail="Unknown status filter.")
        query = query.where(AppUser.status == status_filter)
    rows = db.execute(query).scalars().all()
    return UserList(items=[UserOut.model_validate(r) for r in rows], total=len(rows))


@router.get("/audit-log", response_model=AuditList, summary="Recent user administration events")
def audit_log(
    limit: int = Query(default=100, ge=1, le=500),
    db: Session = Depends(get_db),
    _actor: AuthenticatedUser = Depends(require_permission(Permission.USER_MANAGE)),
) -> AuditList:
    _require_identity_mode()
    rows = db.execute(select(AppUserAuditLog).order_by(AppUserAuditLog.id.desc()).limit(limit)).scalars().all()
    return AuditList(items=[AuditOut.model_validate(r) for r in rows])


@router.post("", response_model=CreateUserResponse, status_code=status.HTTP_201_CREATED, summary="Create a user with a temporary password")
def create_user(
    payload: CreateUserRequest,
    db: Session = Depends(get_db),
    admin: IdentityAdmin = Depends(get_identity_admin),
    actor: AuthenticatedUser = Depends(require_permission(Permission.USER_MANAGE)),
) -> CreateUserResponse:
    _require_identity_mode()
    email = svc.normalize_email(payload.email)
    if "@" not in email or " " in email:
        raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY, detail="Enter a valid e-mail address.")
    role = _valid_role(payload.role)
    if db.execute(select(AppUser.id).where(AppUser.email == email)).first():
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="A user with this e-mail already exists.")
    password = svc.generate_temporary_password()
    uid = _identity_call(admin.create_user, email, password, payload.display_name.strip())
    now = datetime.now(timezone.utc)
    user = AppUser(
        email=email,
        display_name=payload.display_name.strip(),
        role=role.value,
        department=(payload.department or svc.DEFAULT_DEPARTMENT[role]).strip(),
        status=UserStatus.ACTIVE.value,
        auth_uid=uid,
        auth_source="password",
        must_change_password=True,
        temp_password_set_at=now,
        created_by=actor.user_id,
        decided_by=actor.user_id,
        decided_at=now,
    )
    db.add(user)
    svc.audit(db, email, "user_created", actor.user_id, f"Role {role.value}; temporary password issued.")
    try:
        db.commit()
    except Exception:
        db.rollback()
        # Do not leave an orphan sign-in account behind a failed record.
        try:
            admin.delete_user(uid)
        except Exception:  # noqa: BLE001
            pass
        raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Could not save the user.")
    return CreateUserResponse(user=UserOut.model_validate(user), temporary_password=password)


@router.post("/{user_id}/approve", response_model=UserOut, summary="Approve a pending user and assign a role")
def approve_user(
    user_id: int,
    payload: ApproveRequest,
    db: Session = Depends(get_db),
    actor: AuthenticatedUser = Depends(require_permission(Permission.USER_MANAGE)),
) -> UserOut:
    _require_identity_mode()
    user = _get_user(db, user_id)
    if user.status not in (UserStatus.PENDING.value, UserStatus.REJECTED.value):
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="Only pending or rejected users can be approved.")
    _forbid_self(user, actor, "approve")
    role = _valid_role(payload.role)
    user.role = role.value
    user.department = (payload.department or svc.DEFAULT_DEPARTMENT[role]).strip()
    user.status = UserStatus.ACTIVE.value
    user.decided_by = actor.user_id
    user.decided_at = datetime.now(timezone.utc)
    svc.audit(db, user.email, "approved", actor.user_id, f"Role {role.value}.")
    db.commit()
    return UserOut.model_validate(user)


@router.post("/{user_id}/reject", response_model=UserOut, summary="Reject a pending user")
def reject_user(
    user_id: int,
    payload: RejectRequest,
    db: Session = Depends(get_db),
    actor: AuthenticatedUser = Depends(require_permission(Permission.USER_MANAGE)),
) -> UserOut:
    _require_identity_mode()
    user = _get_user(db, user_id)
    if user.status != UserStatus.PENDING.value:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="Only pending users can be rejected.")
    user.status = UserStatus.REJECTED.value
    user.role = None
    user.decided_by = actor.user_id
    user.decided_at = datetime.now(timezone.utc)
    svc.audit(db, user.email, "rejected", actor.user_id, payload.reason)
    db.commit()
    return UserOut.model_validate(user)


@router.patch("/{user_id}", response_model=UserOut, summary="Change a user's role, department or name")
def update_user(
    user_id: int,
    payload: UpdateUserRequest,
    db: Session = Depends(get_db),
    actor: AuthenticatedUser = Depends(require_permission(Permission.USER_MANAGE)),
) -> UserOut:
    _require_identity_mode()
    user = _get_user(db, user_id)
    details = []
    if payload.role is not None:
        if user.status != UserStatus.ACTIVE.value:
            raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="Approve the user before changing the role.")
        new_role = _valid_role(payload.role)
        if new_role.value != user.role:
            _forbid_self(user, actor, "change the role of")
            if user.role == "Admin":
                _keep_one_admin(db, user, "remove the Admin role from")
            details.append(f"role {user.role} -> {new_role.value}")
            user.role = new_role.value
            if payload.department is None:
                user.department = svc.DEFAULT_DEPARTMENT[new_role]
    if payload.department is not None:
        user.department = payload.department.strip()
        details.append("department updated")
    if payload.display_name is not None:
        user.display_name = payload.display_name.strip()
        details.append("name updated")
    if details:
        svc.audit(db, user.email, "updated", actor.user_id, "; ".join(details))
        db.commit()
    return UserOut.model_validate(user)


@router.post("/{user_id}/disable", response_model=UserOut, summary="Disable a user (access stops at once)")
def disable_user(
    user_id: int,
    db: Session = Depends(get_db),
    admin: IdentityAdmin = Depends(get_identity_admin),
    actor: AuthenticatedUser = Depends(require_permission(Permission.USER_MANAGE)),
) -> UserOut:
    _require_identity_mode()
    user = _get_user(db, user_id)
    if user.status == UserStatus.DISABLED.value:
        return UserOut.model_validate(user)
    _forbid_self(user, actor, "disable")
    _keep_one_admin(db, user, "disable")
    # The record is the authority for every request, so it is changed first; the sign-in account follows.
    user.status = UserStatus.DISABLED.value
    user.decided_by = actor.user_id
    user.decided_at = datetime.now(timezone.utc)
    svc.audit(db, user.email, "disabled", actor.user_id)
    db.commit()
    if user.auth_uid:
        try:
            admin.set_disabled(user.auth_uid, True)
        except Exception:  # noqa: BLE001 - access is already denied by the record
            svc.audit(db, user.email, "disable_sync_failed", "system", "Sign-in account could not be disabled; access is still blocked.")
            db.commit()
    return UserOut.model_validate(user)


@router.post("/{user_id}/enable", response_model=UserOut, summary="Enable a disabled user")
def enable_user(
    user_id: int,
    db: Session = Depends(get_db),
    admin: IdentityAdmin = Depends(get_identity_admin),
    actor: AuthenticatedUser = Depends(require_permission(Permission.USER_MANAGE)),
) -> UserOut:
    _require_identity_mode()
    user = _get_user(db, user_id)
    if user.status != UserStatus.DISABLED.value:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="Only disabled users can be enabled.")
    if not user.role:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="This user has no role; approve them with a role instead.")
    if user.auth_uid:
        _identity_call(admin.set_disabled, user.auth_uid, False)
    user.status = UserStatus.ACTIVE.value
    user.decided_by = actor.user_id
    user.decided_at = datetime.now(timezone.utc)
    svc.audit(db, user.email, "enabled", actor.user_id)
    db.commit()
    return UserOut.model_validate(user)


@router.post("/{user_id}/reset-password", response_model=CreateUserResponse, summary="Issue a new temporary password")
def reset_password(
    user_id: int,
    db: Session = Depends(get_db),
    admin: IdentityAdmin = Depends(get_identity_admin),
    actor: AuthenticatedUser = Depends(require_permission(Permission.USER_MANAGE)),
) -> CreateUserResponse:
    _require_identity_mode()
    user = _get_user(db, user_id)
    if not user.auth_uid:
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="This user has not signed in yet and has no sign-in account.")
    if user.auth_source != "password":
        raise HTTPException(status_code=status.HTTP_409_CONFLICT, detail="This user signs in with another service; there is no password to reset.")
    _forbid_self(user, actor, "reset the password of")
    password = svc.generate_temporary_password()
    _identity_call(admin.set_password, user.auth_uid, password)
    user.must_change_password = True
    user.temp_password_set_at = datetime.now(timezone.utc)
    svc.audit(db, user.email, "password_reset", actor.user_id, "Temporary password issued.")
    db.commit()
    return CreateUserResponse(user=UserOut.model_validate(user), temporary_password=password)
